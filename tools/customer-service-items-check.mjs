import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('js/customer-workspace.js','utf8');
const context={arrayValue:v=>Array.isArray(v)?v:[],html:v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'),money:v=>'$'+Number(v).toFixed(2),boardingServiceTaskDisplayName:v=>typeof v==='string'?v:v.serviceName||'Service',boardingServiceTaskQuantity:v=>Number(v.quantity||1)};
vm.createContext(context);
vm.runInContext(source.match(/function customerStayServiceItemsHtml\([\s\S]*?\n\}/)[0],context);
const stay={requests:[{id:'bath',serviceName:'Full Premium Bath',unitPrice:100,quantity:1},{serviceName:'30-min Treadmill Exercise (VIP)',unitPrice:25,quantity:4}]};
const original=JSON.stringify(stay),render=context.customerStayServiceItemsHtml;
let output=render(stay);
assert.equal((output.match(/<li>/g)||[]).length,2);
assert.match(output,/\$100.00 × 1/);assert.match(output,/\$25.00 × 4/);
assert.equal((output.match(/Line total \$100.00/g)||[]).length,2);
assert.equal(JSON.stringify(stay),original,'Display must not modify charges');
assert.match(render({requests:[{serviceName:'Free',unitPrice:0,basePrice:99}]}),/\$0.00 × 1/);
assert.match(render({requests:[{serviceName:'Missing',quantity:3}]}),/Price pending · Qty 3/);
assert.match(render({requests:[{serviceName:'Invalid',unitPrice:'bad'}]}),/Price pending/);
assert.match(render({requests:[{serviceName:'<img onerror="bad">',unitPrice:1.25,quantity:3}]}),/&lt;img/);
assert.match(render({requests:[{serviceName:'Fraction',unitPrice:1.25,quantity:3}]}),/Line total \$3.75/);
assert.match(render({requests:[{id:'bath',serviceName:'Bath'}],pricingSnapshot:{selectedServicePrices:[{serviceId:'bath',unitPrice:42}]}}),/\$42.00 × 1/);
assert.match(render({requests:['Legacy service']}),/Price pending/);
assert.match(render({}),/No service requests/);
assert.match(source,/customerStayServiceItemsHtml\(stay\)/);
console.log('Customer service items passed: names, price x quantity, totals, free and missing prices, saved snapshot fallback, escaping, empty state, no mutation.');

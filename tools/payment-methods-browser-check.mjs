import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.route('**/*.supabase.co/**',r=>r.abort());
try {
  await page.goto((process.env.BASE_URL || 'http://127.0.0.1:8765/') + '?localTest=1&email=qa@example.invalid&role=admin#settingsSetupPage');
  await page.waitForFunction(()=>typeof renderSettingsSetup==='function' && localTestMode);
  await page.waitForTimeout(1200);
  await page.evaluate(()=>{document.querySelectorAll('dialog[open]').forEach(d=>d.close());switchPage('settingsSetupPage');});
  const form=page.locator('#paymentMethodSettingsForm');
  await form.waitFor({state:'visible'});
  assert.equal(await form.locator('[role="switch"]:checked').count(),0);
  const method=name=>form.locator(`[data-payment-method="${name}"]`);
  await method('Cash').locator('[name="enabled"]').check();
  await method('Check').locator('[name="instructions"]').fill('Payable to QA Kennel');
  await method('Zelle').locator('[name="enabled"]').check();
  await form.locator('[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#paymentMethodSaveStatus').textContent.includes('add recipient'));
  assert.equal(await page.evaluate(()=>acceptedPaymentsConfig().Cash.enabled),false,'Invalid form cannot publish partial changes');
  await method('Zelle').locator('[name="account"]').fill('qa@example.invalid');
  await method('Venmo').locator('[name="enabled"]').check();
  await method('Venmo').locator('[name="link"]').fill('https://venmo.com/qa-kennel');
  await method('PayPal').locator('[name="link"]').fill('https://paypal.me/qa-kennel');
  await form.locator('[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#paymentMethodSaveStatus').textContent==='Payment methods saved.');
  await page.reload();
  await page.waitForFunction(()=>typeof renderSettingsSetup==='function' && localTestMode);
  await page.evaluate(()=>{document.querySelectorAll('dialog[open]').forEach(d=>d.close());switchPage('settingsSetupPage');});
  assert(await method('Zelle').locator('[name="enabled"]').isChecked());
  assert.equal(await method('Venmo').locator('[name="link"]').inputValue(),'https://venmo.com/qa-kennel');
  assert.equal(await method('PayPal').locator('[name="link"]').inputValue(),'https://paypal.me/qa-kennel');
  assert(!(await method('PayPal').locator('[name="enabled"]').isChecked()));
  await method('Venmo').locator('[name="enabled"]').uncheck();
  await form.locator('[type="submit"]').click();
  await page.waitForFunction(()=>!acceptedPaymentsConfig().Venmo.enabled);
  assert.equal(await page.evaluate(()=>acceptedPaymentsConfig().Venmo.link),'https://venmo.com/qa-kennel');
  const result=await page.evaluate(async()=>{
    const saved=JSON.stringify(readRecords('appConfig'));
    const real=currentRole; currentRole=()=> 'customer';
    let denied=false;try {await savePaymentMethodSettings(document.querySelector('#paymentMethodSettingsForm'));} catch {denied=true;}
    currentRole=real;
    return {denied,unchanged:saved===JSON.stringify(readRecords('appConfig')),invalid:acceptedPaymentLink('javascript:alert(1)'),html:customerAcceptedPaymentMethodsHtml('BR-QA')};
  });
  assert(result.denied && result.unchanged);assert.equal(result.invalid,'');
  assert(!result.html.includes('Open Venmo'));assert(!result.html.includes('PayPal'));assert(result.html.includes('qa@example.invalid'));
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Settings fit mobile');
  await page.screenshot({path:'outputs/payment-settings-mobile.png',fullPage:true});
  await method('Venmo').locator('[name="enabled"]').check();
  await method('PayPal').locator('[name="enabled"]').check();
  await method('Check').locator('[name="enabled"]').check();
  await form.locator('[type="submit"]').click();
  await page.waitForFunction(()=>acceptedPaymentsConfig().PayPal.enabled);
  const recordsBeforeLink=await page.evaluate(()=>JSON.stringify(readRecords('boardingDog')));
  await page.evaluate(()=>showDetailDialog('Payment instructions',customerAcceptedPaymentMethodsHtml('BR-QA')));
  assert.equal(await page.locator('#detailDialog .payment-method-card').count(),5);
  assert.equal(await page.getByRole('link',{name:'Open Venmo'}).getAttribute('href'),'https://venmo.com/qa-kennel');
  await page.context().route('https://venmo.com/**',r=>r.fulfill({status:200,body:'QA payment destination'}));
  const popupPromise=page.waitForEvent('popup');
  await page.getByRole('link',{name:'Open Venmo'}).click();
  const popup=await popupPromise; await popup.close();
  assert.equal(await page.evaluate(()=>JSON.stringify(readRecords('boardingDog'))),recordsBeforeLink,'Payment link must not write a receipt');
  assert(await page.getByText('How to pay',{exact:true}).isVisible());
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Payment instructions fit mobile');
  await page.screenshot({path:'outputs/payment-instructions-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Payment methods browser checks passed: validation, save/reload, retained disabled details, customer visibility, permissions and mobile layout.');
} finally {await browser.close();}

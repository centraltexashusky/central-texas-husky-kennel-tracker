import assert from 'node:assert/strict';
import {includeOwnedDogs,emptyPedigree,validatePedigree,pedigreeCoefficient as coi,familyOf,completeness,singleGeneCross,testedTraitCrosses,mergePedigree,safePedigreeUrl} from '../js/pedigree-core.js';
const make=(id,sex='Unknown',sireId='',damId='')=>({id,name:id,sex,sireId,damId});
const dogs=[make('g1','Male'),make('g2','Female'),make('s1','Male','g1','g2'),make('s2','Female','g1','g2'),make('u1','Female'),make('u2','Male'),make('c1','Male','s1','u1'),make('c2','Female','u2','s2')];
assert.equal(coi(dogs,'g1','g2'),0);
assert.equal(coi(dogs,'s1','s2'),.25,'full siblings');
assert.equal(coi(dogs,'g1','s2'),.25,'parent offspring');
assert.equal(coi(dogs,'c1','c2'),.0625,'first cousins');
assert.equal(coi(dogs,'s1','c2'),.125,'uncle niece');
assert.equal(coi(dogs,'','g1'),null,'missing direct parent');
const half=[...dogs,make('half','Female','g1','u1')];assert.equal(coi(half,'s1','half'),.125);
const inbred=[...dogs,make('ib','Male','s1','s2')];assert.equal(coi(inbred,'ib','ib'),.625,'inbred ancestor diagonal');
assert.equal(familyOf(half,'s1').siblings.find(d=>d.id==='half').relationship,'Half sibling');
assert.equal(completeness(dogs,'c1',2).known,4);assert.equal(completeness(dogs,'c1',2).total,6);
const base={...emptyPedigree(),dogs};validatePedigree(base);
assert.throws(()=>validatePedigree({...base,dogs:[...dogs,make('g1')]}),/unique/);
assert.throws(()=>validatePedigree({...base,dogs:dogs.map(d=>d.id==='g1'?{...d,sireId:'c1'}:d)}),/ancestor/);
assert.throws(()=>validatePedigree({...base,dogs:dogs.map(d=>d.id==='s1'?{...d,sireId:'missing'}:d)}),/missing/);
assert.throws(()=>validatePedigree({...base,dogs:dogs.map(d=>d.id==='s1'?{...d,sireId:'g2',damId:''}:d)}),/sire/);
assert.throws(()=>validatePedigree({...base,dogs:[{...make('p','Male'),dateOfBirth:'2025-01-01'},{...make('c','Male','p'),dateOfBirth:'2024-01-01'}]}),/birth/);
assert.throws(()=>mergePedigree(base,base),/already exists/);
assert.equal(safePedigreeUrl('javascript:alert(1)'), '');
assert.deepEqual(singleGeneCross('Aa','Aa'),{AA:.25,Aa:.5,aa:.25});assert.deepEqual(singleGeneCross('AA','aa'),{AA:0,Aa:1,aa:0});
const health=[{dogId:'s1',kind:'DNA',test:'Example',variant:'v1',verified:true,model:'Autosomal recessive',genotype:'Aa'},{dogId:'s2',kind:'DNA',test:'Example',variant:'v1',verified:true,model:'Autosomal recessive',genotype:'Aa'}];
assert.equal(testedTraitCrosses(health,'s1','s2')[0].probabilities.aa,.25);
assert.equal(testedTraitCrosses(health.map(h=>({...h,verified:false})),'s1','s2').length,0);
assert(testedTraitCrosses([...health,{...health[0],genotype:'AA'}],'s1','s2')[0].conflict);
console.log('Pedigree core: 21 checks passed (kinship, completeness, family relationships, integrity, imports and genetic evidence).');

const roster=[{id:'owned1',callName:'First',sex:'Male',akcRegistrationNumber:'AKC1'},{id:'owned2',callName:'Second',sex:'Female',akcRegistrationNumber:'AKC1'},{id:'removed',removed:true}];
let seq=0;const synced=includeOwnedDogs(emptyPedigree(),roster,()=>`new${++seq}`);
assert.equal(synced.dogs.length,2);
assert.equal(synced.dogs[1].registrationNumber,'');
assert.match(synced.dogs[1].notes,/needs review/);
synced.dogs[0].notes='Retain research';synced.dogs[0].archived=true;
assert.deepEqual(includeOwnedDogs(synced,roster,()=>`new${++seq}`),synced);
const extended=includeOwnedDogs(synced,[...roster,{id:'later',callName:'Later'}],()=>`new${++seq}`);
assert.equal(extended.dogs.length,3);assert.equal(extended.dogs[2].sex,'Unknown');
assert.equal(synced.dogs.length,2);
console.log('Roster sync: all dogs, repeat sync, later additions, archived preservation and duplicate registration checks passed.');

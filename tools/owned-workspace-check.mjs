const dog={id:'qa',callName:'<script>bad</script>',foodAmount:'1 cup',sex:'Female',medicalCareNotes:'<img onerror="bad">',nextBath:'2026-10-01'};
const html=context.ownedWorkspaceMobileCard(dog);
assert(!html.includes('<script>'));assert(html.includes('&lt;script&gt;'));
assert(!html.includes('<img onerror='));
assert.equal((html.match(/<button /g)||[]).length,2);
assert(html.includes('1 cup'));assert(html.includes('2026-10-01'));
for(const tab of ['Overview','Exercise','Training','Baths','Heat Cycle','Medical / Care Notes']) assert(context.ownedWorkspaceReadHtml(dog,tab).includes(tab.replaceAll('&','&amp;')));
const timeline=context.ownedWorkspaceTimeline({logs:Array.from({length:500},(_,i)=>({id:i,type:'Treadmill',group:'Exercise'}))},'All');
assert.equal((timeline.match(/<article>/g)||[]).length,30);
assert(timeline.includes('Load more history'));
assert(!/\b(fetch|sendPayload|upsertRecord|writeRecords)\(/.test(workspace),'No alternate persistence path');
for(const token of ['if (mobileRoster) renderOwnedDogMobileCards(visibleRecords)','else if (!mobileRoster)','ownedDogMatchesCareFilter(record) && (!query || matches(record, query))','setupOwnedWorkspace(normalized)','ownedWorkspaceTimeline(record || {}, filter)']) assert(daily.includes(token),token);
assert(workspace.includes('setFormValues(document.getElementById(\'ourDogForm\'), dog)'),'Editing starts from current saved care data');

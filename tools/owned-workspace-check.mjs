import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const workspace=fs.readFileSync('js/owned-workspace.js','utf8');
const daily=fs.readFileSync('js/daily.js','utf8');
const shared=fs.readFileSync('js/shared.js','utf8');
const settings=fs.readFileSync('js/settings.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('owned-workspace.css','utf8');
new vm.Script(workspace);
const context=vm.createContext({document:{addEventListener(){}},matchMedia:()=>({addEventListener(){}}),escapeHtml:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;'),ownedDogDisplayName:d=>d.callName,profilePhotoDirectSource:()=>'',profilePhotoAccessAttrs:()=>'',avatarText:()=> 'Q',ownedDogCareTagsHtml:()=>'<span>Training due</span>',ownedDogCareAlertNotes:d=>d.medicalCareNotes||'',ownedDogActivityLogs:d=>d.logs||[],ownedDogActivityLogCardHtml:log=>'<article>'+log.id+'</article>'});

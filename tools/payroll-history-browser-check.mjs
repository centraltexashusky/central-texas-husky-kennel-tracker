import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true,channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1080}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('**/*.supabase.co/**',route=>route.abort());
try {
  await page.goto('http://127.0.0.1:8765/?localTest=1&email=payroll-qa@example.invalid&role=admin#timesheetPage');
  await page.waitForFunction(()=>typeof appInitialized!=='undefined'&&appInitialized&&typeof renderTimesheet==='function');
  await page.evaluate(async()=>{
    if (supabaseClient || !localTestMode) throw Error('Not isolated');
    document.getElementById('detailDialog').close();
    localStorage.removeItem('kennel-qa-payroll-receipts');
    payrollReceiptState.loaded=false;
    window.qaPayrollWeek=addDays(payrollWeekStart(payrollToday()),-14);
    const week=window.qaPayrollWeek;
    writeRecords('settingsUser',[{id:'qa-payroll-staff',type:'settingsUser',name:'Avery QA',email:'avery-payroll@example.invalid',role:'helper',hourlyRate:10}]);
    writeRecords('timesheet',Array.from({length:2},(_,i)=>({id:'qa-paid-clock-'+i,type:'timesheet',date:addDays(week,i*2),helperName:'Avery QA',helperEmail:'avery-payroll@example.invalid',clockInTime:addDays(week,i*2)+'T09:00:00-06:00',clockOutTime:addDays(week,i*2)+'T13:00:00-06:00',hours:i?2.5:1.25,note:'Fictional payroll test'})));
    await ensurePayrollPaymentsLoaded(true);
    timesheetFilterStart=week;timesheetFilterEnd=addDays(week,6);timesheetTab='payroll';renderTimesheet();
  });
  await page.locator('[data-payroll-action="rate"]').click();
  await page.locator('#payrollRateForm [name="rate"]').fill('20');
  await page.locator('#payrollRateForm [name="effective"]').fill(await page.evaluate(()=>addDays(window.qaPayrollWeek,2)));
  await page.locator('#payrollRateForm button[type="submit"]').click();
  await page.waitForFunction(()=>!document.getElementById('detailDialog').open);
  assert.match(await page.locator('#payrollRows').innerText(),/Multiple rates/);
  assert.match(await page.locator('#payrollRows').innerText(),/62.50/);
  await page.locator('[data-payroll-action="review"]').click();
  await page.locator('#payrollPaymentForm [name="method"]').selectOption('Check');
  await page.locator('#payrollPaymentForm [name="reference"]').fill('QA-001');
  await page.locator('#payrollPaymentForm [name="confirmed"]').check();
  await page.locator('#detailDialog').screenshot({path:'/private/tmp/payroll-confirm-desktop.png'});
  await page.locator('#payrollPaymentForm button[type="submit"]').click();
  await page.waitForFunction(()=>!document.getElementById('detailDialog').open);
  assert.match(await page.locator('#payrollHistory').innerText(),/Paid & locked/);
  await page.locator('[data-payroll-action="receipt"]').click();
  assert.match(await page.locator('#detailDialogBody').innerText(),/62.50 gross paid/);
  await page.locator('#closeDetailDialog').click();
  // New rates do not reprice paid payroll; a late clock is visibly unconfirmed.
  await page.locator('[data-payroll-action="rate"]').click();
  await page.locator('#payrollRateForm [name="rate"]').fill('30');
  await page.locator('#payrollRateForm [name="effective"]').fill(await page.evaluate(()=>window.qaPayrollWeek));
  await page.locator('#payrollRateForm button[type="submit"]').click();
  await page.waitForFunction(()=>!document.getElementById('detailDialog').open);
  assert.match(await page.locator('#payrollRows').innerText(),/62.50/);
  await page.evaluate(()=>{
    const rows=readRecords('timesheet');
    writeRecords('timesheet',[...rows,{...rows[0],id:'qa-late-clock',hours:1}]);renderTimesheet();
  });
  assert.match(await page.locator('#payrollHistory').innerText(),/Partly paid/);
  assert.match(await page.locator('#payrollHistory').innerText(),/30.00/);
  await page.locator('#payrollHistory').screenshot({path:'/private/tmp/payroll-history-desktop.png'});
  // Review becomes stale while open: confirmation must reject rather than guess.
  await page.locator('[data-payroll-action="review"]').click();
  await page.evaluate(()=>{const rows=readRecords('timesheet');rows.find(row=>row.id==='qa-late-clock').hours=2;writeRecords('timesheet',rows);});
  await page.locator('#payrollPaymentForm [name="method"]').selectOption('Cash');
  await page.locator('#payrollPaymentForm [name="confirmed"]').check();
  await page.locator('#payrollPaymentForm button[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('.payroll-form-error')?.textContent.includes('changed since review'));
  await page.locator('#closeDetailDialog').click();
  await page.locator('[data-payroll-action="refresh"]').click();
  await page.setViewportSize({width:390,height:844});
  const mobileLabels=await page.locator('.payroll-history-table td').evaluateAll(cells=>cells.map(cell=>getComputedStyle(cell,'::before').content));
  assert.deepEqual(mobileLabels,['"Week / employee"','"Hours"','"Gross pay"','"Paid gross"','"Unconfirmed gross"','"Status / action"'],'Mobile labels match the new payroll columns.');
  await page.waitForTimeout(3500);
  await page.locator('#payrollHistory').screenshot({path:'/private/tmp/payroll-history-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Mobile payroll must not overflow the viewport.');
  await page.reload();
  await page.waitForFunction(()=>typeof appInitialized!=='undefined'&&appInitialized&&typeof renderTimesheet==='function');
  await page.evaluate(()=>{document.getElementById('detailDialog').close();timesheetTab='payroll';renderTimesheet();});
  await page.waitForFunction(()=>document.querySelector('#payrollHistory')?.textContent.includes('Partly paid'));
  assert.equal(await page.evaluate(()=>payrollReceiptCache().rows.length),1,'Reload preserves one payment, without duplicates.');
  assert.equal(await page.evaluate(()=>readRecords('settingsUser')[0].hourlyRateHistory.length),3);
  await page.evaluate(()=>{currentUser.role='staff';renderTimesheet();});
  assert.equal(await page.locator('#payrollHistory').innerText(),'','Staff cannot see admin payroll history.');
  assert.deepEqual(errors,[]);
  console.log('Payroll browser checks passed: effective raise, fixed payment, receipt, supplemental hours, stale-save rejection, reload and mobile privacy.');
} finally { await browser.close(); }

 blocked:=false;begin
  insert into cuddle_stay.payroll_payments(staff_id,week_start,paid_date,payment_method,snapshot)
  select staff,(s->>'weekStart')::date,'2026-11-01','QA duplicate',s from jsonb_array_elements(snapshots) s;
 exception when raise_exception then blocked:=true;end;

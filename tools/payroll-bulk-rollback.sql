set local role authenticated;
do $$ declare blocked boolean:=false;begin
 begin perform cuddle_stay.payroll_bulk_preview('[]');exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'Staff can bulk-preview payroll';end if;

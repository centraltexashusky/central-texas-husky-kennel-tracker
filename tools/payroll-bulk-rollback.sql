-- Fictional bulk payroll checks. The entire transaction, including receipts, rolls back.
begin;
select set_config('request.jwt.claim.sub',(select user_id::text from shared.organization_members where organization_id=cuddle_stay_private.cuddle_stay_organization_id() and role in ('admin','owner') order by created_at limit 1),true);
set local role authenticated;
do $$
declare staff text:='payroll-bulk-qa-'||gen_random_uuid(); a text:='payroll-bulk-qa-'||gen_random_uuid(); b text:='payroll-bulk-qa-'||gen_random_uuid();
 snapshots jsonb; selection jsonb; blocked boolean; payments_before int;
begin
 select count(*) into payments_before from cuddle_stay.payroll_payments;
 insert into cuddle_stay.kennel_records(id,type,organization_id,payload) values(staff,'settingsUser',cuddle_stay_private.cuddle_stay_organization_id(),jsonb_build_object('id',staff,'type','settingsUser','name',staff,'email',staff||'@example.invalid','role','helper','hourlyRate',10));
 insert into cuddle_stay.kennel_records(id,type,organization_id,payload)
 select id,'timesheet',cuddle_stay_private.cuddle_stay_organization_id(),jsonb_build_object('id',id,'type','timesheet','helperEmail',staff||'@example.invalid','date',d,'hours',h,'clockInTime',d||'T09:00:00-05:00','clockOutTime',d||'T11:00:00-05:00') from(values(a,'2026-10-12',1),(b,'2026-10-19',2)) t(id,d,h);
 selection:=jsonb_build_array(jsonb_build_object('staffId',staff,'weekStart','2026-10-12'),jsonb_build_object('staffId',staff,'weekStart','2026-10-19'));
 snapshots:=cuddle_stay.payroll_bulk_preview(selection);
 if jsonb_array_length(snapshots)<>2 or (select sum((s->>'amountCents')::int) from jsonb_array_elements(snapshots) s)<>3000 then raise exception 'Bulk preview total mismatch'; end if;
 blocked:=false;begin perform cuddle_stay.payroll_bulk_preview(selection||selection);exception when raise_exception then blocked:=true;end;
 if not blocked then raise exception 'Duplicate selection accepted';end if;
 blocked:=false;begin perform cuddle_stay.payroll_bulk_preview(jsonb_build_array(jsonb_build_object('staffId',staff,'weekStart',date_trunc('week',now() at time zone 'America/Chicago')::date)));exception when raise_exception then blocked:=true;end;
 if not blocked then raise exception 'Current week accepted for bulk review';end if;
 update cuddle_stay.kennel_records set payload=jsonb_set(payload,'{hours}','3') where id=b;
 blocked:=false;

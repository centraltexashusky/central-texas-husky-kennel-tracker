  -- This is the same single INSERT statement generated by PostgREST's array insert.
  insert into cuddle_stay.payroll_payments(staff_id,week_start,paid_date,payment_method,snapshot)
  select staff,(s->>'weekStart')::date,'2026-11-01','QA only',s from jsonb_array_elements(snapshots) s order by s->>'weekStart';
 exception when serialization_failure then blocked:=true;end;
 if not blocked or (select count(*) from cuddle_stay.payroll_payments)<>payments_before or exists(select 1 from cuddle_stay.payroll_payment_items where timesheet_id in(a,b)) then raise exception 'Failed bulk insert partially persisted';end if;
 update cuddle_stay.kennel_records set payload=jsonb_set(payload,'{hours}','2') where id=b;
 insert into cuddle_stay.payroll_payments(staff_id,week_start,paid_date,payment_method,reference,snapshot)
 select staff,(s->>'weekStart')::date,'2026-11-01','QA only','QA-'||(s->>'weekStart'),s from jsonb_array_elements(snapshots) s order by s->>'weekStart';
